function brandSlug(name) {
  return String(name).toLowerCase().trim().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "");
}

async function seedCategories() {
  const categoryMap = new Map();

  // Top-level categories first (no parent).
  const tops = CATALOG.categories.filter((c) => !c.children || c.children.length === 0);
  for (const c of tops) {
    const doc = await Category.create({
      slug: c.slug,
      name: c.name,
      description: c.description,
      parentId: null,
      level: 0,
      productCount: c.productCount,
      sortOrder: 0,
      isActive: true,
    });
    categoryMap.set(c.slug, doc._id);
  }

  // Then categories that have children (insert parent, then its children).
  const parents = CATALOG.categories.filter((c) => c.children && c.children.length > 0);
  for (const p of parents) {
    let parentDoc = await Category.findOne({ slug: p.slug });
    if (!parentDoc) {
      parentDoc = await Category.create({
        slug: p.slug,
        name: p.name,
        description: p.description,
        parentId: null,
        level: 0,
        productCount: p.productCount,
        sortOrder: 0,
        isActive: true,
      });
    }
    categoryMap.set(p.slug, parentDoc._id);
    for (const child of p.children) {
      const childDoc = await Category.create({
        slug: child.slug,
        name: child.name,
        description: child.description,
        parentId: parentDoc._id,
        level: 1,
        productCount: child.productCount,
        sortOrder: 0,
        isActive: true,
      });
      categoryMap.set(child.slug, childDoc._id);
    }
  }
  return categoryMap;
}

async function seedBrands() {
  const brandMap = new Map();
  for (const b of CATALOG.brands) {
    const doc = await Brand.create({
      slug: b.slug,
      name: b.name,
      productCount: b.productCount,
      isActive: true,
    });
    brandMap.set(b.slug, doc._id);
  }
  return brandMap;
}

function mapProduct(p, brandMap, categoryMap) {
  const brandId = brandMap.get(brandSlug(p.brand));
  const categoryId = categoryMap.get(p.category);
  const topCategoryId = categoryMap.get(p.topCategory);

  const variants = p.variants.map((v) => ({
    _id: new mongoose.Types.ObjectId(),
    sku: v.sku,
    name: v.name,
    options: v.options,
    priceCents: v.priceCents,
    compareAtCents: v.compareAtCents ?? null,
    isDefault: v.isDefault,
    stock: v.stock,
    inStock: v.inStock,
  }));
  const defaultVariant = variants.find((v) => v.isDefault) || variants[0];

  return {
    slug: p.slug,
    name: p.name,
    description: p.description,
    brandId,
    brandName: p.brand,
    categoryId,
    categorySlug: p.category,
    topCategoryId,
    topCategorySlug: p.topCategory,
    badge: p.badge,
    badgeLabel: p.badgeLabel,
    isPreorder: p.isPreorder,
    releaseDate: p.releaseDate ? new Date(p.releaseDate) : null,
    priceCents: p.priceCents,
    compareAtCents: p.compareAtCents ?? null,
    fromPriceCents: p.fromPriceCents,
    variantCount: p.variantCount,
    createdAt: new Date(p.createdAt),
    rating: p.rating,
    reviewCount: p.reviewCount,
    stock: p.stock,
    inStock: p.inStock,
    defaultVariantId: defaultVariant._id,
    imageUrl: p.imageUrl,
    card: p.card,
    variants,
    specs: p.specs,
    images: [],
    isActive: true,
  };
}

async function seedProducts(brandMap, categoryMap) {
  const docs = CATALOG.products.map((p) => mapProduct(p, brandMap, categoryMap));
  const inserted = await Product.insertMany(docs, { ordered: false });
  return inserted;
}

async function seedBanners() {
  const docs = CATALOG.banners.map((b) => ({
    eyebrow: b.eyebrow,
    title: b.title,
    subtitle: b.subtitle,
    ctaLabel: b.ctaLabel,
    ctaLink: b.ctaLink,
    imageUrl: b.imageUrl,
    card: b.card,
    isActive: true,
    sortOrder: b.id,
    startDate: null,
    endDate: null,
  }));
  return await Banner.insertMany(docs, { ordered: false });
}

async function seedShippingRates() {
  const docs = CATALOG.rates.map((r) => ({
    region: r.region,
    feeCents: r.feeCents,
    freeOverCents: r.freeOverCents ?? null,
    etaDays: r.etaDays,
    isActive: true,
  }));
  return await ShippingRate.insertMany(docs, { ordered: false });
}

async function main() {
  await connect();

  // Clear existing data (idempotent re-seed)
  await Product.deleteMany({});
  await Category.deleteMany({});
  await Brand.deleteMany({});
  await Banner.deleteMany({});
  await ShippingRate.deleteMany({});

  const categoryMap = await seedCategories();
  const brandMap = await seedBrands();
  const products = await seedProducts(brandMap, categoryMap);
  await seedBanners();
  await seedShippingRates();

  console.log("[seed] Categories:", categoryMap.size);
  console.log("[seed] Brands:", brandMap.size);
  console.log("[seed] Products:", products.length);
  console.log("[seed] Done.");

  await disconnect();
}

main().catch((err) => {
  console.error("[seed] Failed:", err);
  process.exit(1);
});
